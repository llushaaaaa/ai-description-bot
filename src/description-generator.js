const Groq = require('groq-sdk');
const { Octokit } = require('@octokit/rest');

const groq = new Groq({ apiKey: process.env.GROQ_API_KEY });
const octokit = new Octokit({ auth: process.env.GITHUB_TOKEN });

const DESCRIPTION_PROMPT = `Ты эксперт по написанию чётких и понятных описаний PR.
Проанализируй предоставленный diff и сгенерируй структурированное описание PR на русском языке.

Твой ответ должен следовать этому формату:

## Краткое описание
Краткий обзор того, что делает этот PR (1-2 предложения)

## Изменения
- Список конкретных изменений
- Будь кратким, но информативным
- Группируй связанные изменения вместе

## Дополнительные заметки
Важный контекст, шаги миграции или на что ревьюерам стоит обратить внимание.

Правила:
- Пиши кратко и профессионально
- Фокусируйся на том, ЧТО изменилось и ЗАЧЕМ, а не КАК
- Используй маркированные списки для ясности
- Если изменение небольшое, описание тоже должно быть коротким
- ВСЕГДА пиши на русском языке`;

async function getChangedFiles(owner, repo, pullNumber) {
  const { data: files } = await octokit.pulls.listFiles({
    owner,
    repo,
    pull_number: pullNumber,
  });
  return files;
}

async function getPullRequest(owner, repo, pullNumber) {
  const { data: pr } = await octokit.pulls.get({
    owner,
    repo,
    pull_number: pullNumber,
  });
  return pr;
}

async function generateDescription(diff, prTitle) {
  const completion = await groq.chat.completions.create({
    messages: [
      { role: 'system', content: DESCRIPTION_PROMPT },
      { 
        role: 'user', 
        content: `PR Title: ${prTitle}\n\nChanges:\n${diff}` 
      }
    ],
    model: 'llama-3.3-70b-versatile',
    temperature: 0.3,
    max_tokens: 2048,
  });

  return completion.choices[0]?.message?.content || 'Unable to generate description';
}

async function updatePRDescription(owner, repo, pullNumber, description) {
  await octokit.pulls.update({
    owner,
    repo,
    pull_number: pullNumber,
    body: description,
  });
}

async function run() {
  const [owner, repo] = process.env.GITHUB_REPOSITORY.split('/');
  const pullNumber = parseInt(process.env.PR_NUMBER, 10);

  console.log(`Generating description for PR #${pullNumber} in ${owner}/${repo}`);

  const pr = await getPullRequest(owner, repo, pullNumber);
  
  if (pr.body && pr.body.trim().length > 50) {
    console.log('PR already has a description, skipping...');
    return;
  }

  const files = await getChangedFiles(owner, repo, pullNumber);

  const ignoredPatterns = [
    'package-lock.json',
    'yarn.lock',
    'pnpm-lock.yaml',
    'node_modules',
    '.angular',
    '.min.js',
    '.min.css',
    '.map',
    'dist/',
    'build/',
  ];

  const relevantFiles = files.filter((f) => {
    return !ignoredPatterns.some(pattern => f.filename.includes(pattern));
  });

  if (relevantFiles.length === 0) {
    console.log('No relevant files found');
    return;
  }

  const diff = relevantFiles
    .map((f) => `### ${f.filename}\n\`\`\`diff\n${f.patch || ''}\n\`\`\``)
    .join('\n\n');

  const truncatedDiff = diff.slice(0, 25000);

  console.log(`Analyzing ${relevantFiles.length} files...`);
  const description = await generateDescription(truncatedDiff, pr.title);

  const finalDescription = `${description}\n\n---\n*🤖 Generated by AI Description Bot*`;

  console.log('Updating PR description...');
  await updatePRDescription(owner, repo, pullNumber, finalDescription);

  console.log('Description updated successfully!');
}

run().catch((err) => {
  console.error('Error:', err.message);
  process.exit(1);
});
